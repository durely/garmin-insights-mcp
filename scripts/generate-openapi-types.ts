// Generates src/garmin/generated/openapi.ts from the spec fetched by fetch-openapi.ts.
// Garmin's descriptions, summaries and examples are their text, so they're stripped from the
// committed types and written to a gitignored openapi.local.md next to them instead.
//
// Usage: node scripts/generate-openapi-types.ts   (or `npm run openapi` to fetch first)

import { readFile, writeFile } from "node:fs/promises";
import openapiTS, { astToString } from "openapi-typescript";

const SPEC_FILE = "openapi/garmin-personal-api.json";
const TYPES_FILE = "src/garmin/generated/openapi.ts";
const DOCS_FILE = "src/garmin/generated/openapi.local.md";

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };
type JsonObject = { [key: string]: Json };

const isObject = (v: Json | undefined): v is JsonObject =>
  typeof v === "object" && v !== null && !Array.isArray(v);

// Keywords that only carry Garmin's prose or sample values, not type information.
const DOC_KEYWORDS = new Set(["description", "summary", "title", "example", "examples", "externalDocs"]);
// Objects whose keys are names (properties, paths, status codes, …), never keywords.
const NAME_MAPS = new Set([
  "properties",
  "patternProperties",
  "schemas",
  "paths",
  "responses",
  "parameters",
  "headers",
  "content",
  "requestBodies",
  "securitySchemes",
  "encoding",
  "links",
  "callbacks",
  "variables",
]);

function stripDocs(node: Json, keysAreNames = false): Json {
  if (Array.isArray(node)) return node.map((v) => stripDocs(v));
  if (!isObject(node)) return node;
  const out: JsonObject = {};
  for (const [key, value] of Object.entries(node)) {
    if (!keysAreNames && DOC_KEYWORDS.has(key)) continue;
    out[key] = stripDocs(value, !keysAreNames && NAME_MAPS.has(key) && isObject(value));
  }
  return out;
}

// ---- Local documentation ----

const oneLine = (text: Json | undefined) =>
  typeof text === "string"
    ? text
        .replace(/\s*\n\s*/g, " ")
        .replace(/\|/g, "\\|")
        .trim()
    : "";

function typeOf(schema: Json | undefined): string {
  if (!isObject(schema)) return "";
  if (typeof schema.$ref === "string") return schema.$ref.split("/").pop() ?? "";
  if (schema.type === "array") return `${typeOf(schema.items)}[]`;
  const base = typeof schema.type === "string" ? schema.type : "object";
  const extra = Array.isArray(schema.enum) ? ` (${schema.enum.join(", ")})` : "";
  return `${base}${typeof schema.format === "string" ? ` (${schema.format})` : ""}${extra}`;
}

function docsMarkdown(spec: JsonObject): string {
  const info = isObject(spec.info) ? spec.info : {};
  const lines = [
    `# ${oneLine(info.title)} ${oneLine(info.version)}: descriptions`,
    "",
    `> Generated by \`npm run openapi\` from Garmin's OpenAPI spec. This is Garmin's text, so it stays local (\`*.local.md\` is gitignored).`,
    "",
    "## Endpoints",
  ];
  for (const [path, item] of Object.entries(isObject(spec.paths) ? spec.paths : {})) {
    if (!isObject(item)) continue;
    for (const [method, op] of Object.entries(item)) {
      if (!isObject(op)) continue;
      lines.push("", `### ${method.toUpperCase()} ${path}`, "");
      if (op.summary) lines.push(oneLine(op.summary), "");
      if (op.description && op.description !== op.summary) lines.push(oneLine(op.description), "");
      const params = Array.isArray(op.parameters) ? op.parameters.filter(isObject) : [];
      for (const p of params) {
        const required = p.required ? ", required" : "";
        const example = p.example !== undefined ? ` Example: \`${JSON.stringify(p.example)}\`.` : "";
        lines.push(
          `- \`${oneLine(p.name)}\` (${oneLine(p.in)}, ${typeOf(p.schema)}${required}): ${oneLine(p.description)}${example}`,
        );
      }
      for (const [code, res] of Object.entries(isObject(op.responses) ? op.responses : {})) {
        if (!isObject(res)) continue;
        const media = isObject(res.content) ? Object.values(res.content).find(isObject) : undefined;
        const returns = media ? ` → \`${typeOf(media.schema)}\`` : "";
        lines.push(`- **${code}**: ${oneLine(res.description)}${returns}`);
      }
    }
  }
  lines.push("", "## Schemas");
  const schemas =
    isObject(spec.components) && isObject(spec.components.schemas) ? spec.components.schemas : {};
  for (const [name, schema] of Object.entries(schemas)) {
    if (!isObject(schema)) continue;
    lines.push("", `### ${name}`, "");
    if (schema.description) lines.push(oneLine(schema.description), "");
    const props = isObject(schema.properties) ? Object.entries(schema.properties) : [];
    if (props.length === 0) continue;
    lines.push("| Field | Type | Description | Example |", "| --- | --- | --- | --- |");
    for (const [prop, ps] of props) {
      if (!isObject(ps)) continue;
      const example = ps.example !== undefined ? `\`${oneLine(JSON.stringify(ps.example))}\`` : "";
      lines.push(`| \`${prop}\` | ${oneLine(typeOf(ps))} | ${oneLine(ps.description)} | ${example} |`);
    }
  }
  return `${lines.join("\n")}\n`;
}

// ---- Main ----

const spec = JSON.parse(await readFile(SPEC_FILE, "utf8")) as JsonObject;
await writeFile(DOCS_FILE, docsMarkdown(spec));

const ast = await openapiTS(stripDocs(spec) as Parameters<typeof openapiTS>[0]);
const banner = [
  "/**",
  " * This file was auto-generated by openapi-typescript (scripts/generate-openapi-types.ts).",
  " * Do not make direct changes to the file.",
  " * Garmin's descriptions are left out; run `npm run openapi` to get them in openapi.local.md.",
  " */",
  "",
  "",
].join("\n");
await writeFile(TYPES_FILE, banner + astToString(ast));
console.error(`Wrote ${TYPES_FILE} and ${DOCS_FILE}`);
